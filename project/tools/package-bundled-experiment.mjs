import {randomBytes} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {mkdir,readFile,unlink,writeFile} from 'node:fs/promises';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {buildBundledExperiment} from './build-bundled-experiment.mjs';
import {assembleBundledExperiment} from './assemble-bundled-experiment.mjs';
import {buildProvenance} from './build-provenance.mjs';

if(process.platform!=='win32')throw new Error('Windows packaging must run on Windows.');
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const args=process.argv.slice(2);
if(args.length>1 || (args.length===1 && args[0]!=='--release'))throw new Error('Usage: node tools/package-bundled-experiment.mjs [--release]');
const release=args[0]==='--release';
const {version}=JSON.parse(await readFile(join(root,'package.json'),'utf8'));
const identity=await readFile(join(root,'tools/windows/clipnote.rc'),'utf8');
if(!/^\d+\.\d+\.\d+$/.test(version) || !identity.includes('PRODUCTVERSION '+version.replaceAll('.',',')+',0'))throw new Error('Windows resource and npm versions differ.');
const built=await buildBundledExperiment(),parent=resolve(root,'../.local/releases');
await mkdir(parent,{recursive:true});
const output=join(parent,release?'ClipNote-win-x64-'+version:'ClipNote-candidate-'+randomBytes(8).toString('hex'));
await assembleBundledExperiment({runtimeDir:join(root,'node_modules/electron/dist'),buildDir:built.output,projectRoot:root,outputDir:output,release});
const resourceDir=join(root,'tools/windows'),object=join(output,'clipnote-res.o'),library=join(output,'clipnote-res.dll');
execFileSync('windres',['clipnote.rc','-O','coff','-o',object],{cwd:resourceDir});
execFileSync('gcc',['-shared',object,'-o',library]);
execFileSync('powershell.exe',['-NoProfile','-File',join(resourceDir,'update-identity.ps1'),'-Source',library,'-Target',join(output,'ClipNote.exe')]);
await unlink(object);await unlink(library);
const info=await buildProvenance(root,join(output,'ClipNote.exe'));
if(release && info.sourceDirty)throw new Error('Windows release requires a clean source commit.');
await writeFile(join(output,'build-info.json'),JSON.stringify({...info,bundling:release?'windows-release':'internal-experiment',appVersion:release?version:version+'-candidate',npmNoticeCount:built.noticeCount},null,2));
console.log((release?'Windows release: ':'Internal candidate: ')+output);
