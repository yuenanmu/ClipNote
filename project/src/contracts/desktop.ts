import type { SourceDocument } from './source.ts';
import type { SourceErrorCode } from '../modules/source/errors.ts';
import type { LibraryState, SavedRevision } from './storage.ts';
import type { StorageErrorCode } from '../modules/storage/errors.ts';
import type { NoteEntry, ReaderDocument } from './reader.ts';
import type { ReaderErrorCode } from '../modules/reader/errors.ts';
import type { ApiConfigInput, ApiResult, ApiState } from './api.ts';
import type { WorkflowResult } from './workflow.ts';
import type {WorkspaceKind,WorkspaceActions,WorkspaceAction,WorkspaceResult,WorkspaceChange,BatchConfig,BatchState,SavedResult,SavePreview,ExportPreview,ExportSelection,FileOperationResult} from './workspace.ts';
export type ReaderResult<T> = { status: 'ok'; value: T } | { status: 'cancelled' } | { status: 'error'; error: { code: ReaderErrorCode; message: string } };
export type ImportErrorCode = SourceErrorCode | 'IMPORT_BUSY' | 'FORBIDDEN_REQUEST' | 'IMPORT_FAILED';
export type ImportResult = { status: 'imported'; document: SourceDocument; entryId?:string } | { status: 'cancelled' } | { status: 'error'; error: { code: ImportErrorCode; message: string } };
export type StorageResult<T> = { status: 'ok'; value: T } | { status: 'cancelled' } | { status: 'error'; error: { code: StorageErrorCode | 'FORBIDDEN_REQUEST' | 'STORAGE_BUSY'; message: string; draftId?: string } };
export interface DesktopApi {
  workspace<A extends WorkspaceAction>(kind: WorkspaceKind, action: A, ...args: WorkspaceActions[A]['args']): Promise<WorkspaceResult<WorkspaceActions[A]['value']>>;
  onWorkspaceChanged(listener:(change:WorkspaceChange)=>void):()=>void;
  savedResults():Promise<WorkspaceResult<SavedResult[]>>;
  prepareResult(id:string,folderId?:string,name?:string):Promise<WorkspaceResult<SavePreview>>;
  saveResult(token:string):Promise<WorkspaceResult<null>>;
  archivePreview(folderId:string):Promise<WorkspaceResult<ExportPreview>>;
  archiveExport(folderId:string,selected:ExportSelection[]):Promise<WorkspaceResult<FileOperationResult[]>>;
  batchState(): Promise<WorkspaceResult<BatchState>>;
  batchPrepare(ids: string[], folderId: string, expected: BatchConfig): Promise<WorkspaceResult<BatchState>>;
  batchStart(): Promise<WorkspaceResult<BatchState>>;
  batchCancel(): Promise<WorkspaceResult<BatchState>>;
  batchRetry(ids: string[]): Promise<WorkspaceResult<BatchState>>;
  workflowState(): Promise<WorkflowResult>;
  workflowStart(sourceId: string, expected: { baseUrl: string; model: string; instructions?: string }): Promise<WorkflowResult>;
  workflowCancel(): Promise<WorkflowResult>;
  workflowRetrySave(): Promise<WorkflowResult>;
  apiState(): Promise<ApiResult<ApiState>>;
  apiSave(input: ApiConfigInput): Promise<ApiResult<ApiState>>;
  apiTest(): Promise<ApiResult<null>>;
  apiModels(input: { baseUrl: string; apiKey: string }): Promise<ApiResult<string[]>>;
  apiCancel(): Promise<ApiResult<null>>;
  noteList(): Promise<ReaderResult<NoteEntry[]>>;
  noteAdd(): Promise<ReaderResult<ReaderDocument>>;
  noteOpen(noteId: string): Promise<ReaderResult<ReaderDocument>>;
  noteRemove(noteId: string): Promise<ReaderResult<null>>;
  noteRelink(noteId: string): Promise<ReaderResult<ReaderDocument>>;
  noteSource(sourceId: string): Promise<ReaderResult<ReaderDocument>>;
  importSource(): Promise<ImportResult>;
  libraryState(): Promise<StorageResult<LibraryState>>;
  chooseLibrary(): Promise<StorageResult<LibraryState>>;
  saveSource(sourceId: string): Promise<StorageResult<SavedRevision>>;
  resumeSave(draftId: string): Promise<StorageResult<SavedRevision>>;
  openRevision(sourceId: string, revisionId: string): Promise<StorageResult<{ document: SourceDocument; revision: SavedRevision }>>;
  readerOpen(): Promise<ReaderResult<ReaderDocument>>;
  readerWorkspace(id:string):Promise<ReaderResult<ReaderDocument>>;
  readerRevision(sourceId: string, revisionId: string): Promise<ReaderResult<ReaderDocument>>;
  readerRefresh(readerId: string): Promise<ReaderResult<ReaderDocument>>;
  readerExternal(readerId: string): Promise<ReaderResult<null>>;
  readerLink(readerId: string, url: string): Promise<ReaderResult<null>>;
}
